import puppeteer from 'puppeteer-core'
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe'
const BASE = 'http://localhost:5173'
const b = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox'] })
const p = await b.newPage()
p.on('console', (m) => console.log(`  [${m.type()}]`, m.text().slice(0, 300)))
p.on('pageerror', (e) => console.log('  PAGEERR', e.message))
p.on('requestfailed', (r) => console.log('  REQFAIL', r.url(), r.failure()?.errorText))
p.on('response', (r) => { if (r.url().includes('/submissions') || r.status() >= 400) console.log('  RESP', r.status(), r.request().method(), r.url().replace(BASE, '').slice(0, 90)) })
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const setInput = (sel, v) => p.$eval(sel, (el, val) => { const s = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; s.call(el, val); el.dispatchEvent(new Event('input', { bubbles: true })) }, v)

await p.goto(`${BASE}/login`, { waitUntil: 'networkidle0' })
await p.evaluate(() => localStorage.clear())
await p.goto(`${BASE}/login`, { waitUntil: 'networkidle0' })
await p.reload({ waitUntil: 'networkidle0' })
await setInput('#email', 'student@example.com')
await setInput('#password', 'demo1234')
await p.evaluate(() => document.querySelector('form').requestSubmit())
await p.waitForFunction(() => !location.pathname.startsWith('/login'), { timeout: 15000 })
await wait(3000)
await p.goto(`${BASE}/student/assessments`, { waitUntil: 'networkidle0' })
await wait(2000)
await p.evaluate(() => [...document.querySelectorAll('a')].find((e) => /open/i.test(e.textContent))?.click())
await wait(1000)
await p.waitForFunction(() => location.pathname.includes('/student/assessments/'), { timeout: 10000 })
console.log('--- on assessment page, waiting for scenario ---')
await p.waitForFunction(() => /your scenario/i.test(document.body.innerText), { timeout: 45000 }).catch(() => console.log('  scenario did not appear'))
await wait(1000)
const inp = await p.$('input[type=file]')
console.log('file input present:', !!inp)
await inp.uploadFile('e:/claude-workshop/Evaluation system/backend/fixtures/demo_solution.zip')
console.log('--- uploaded file, waiting 12s ---')
await wait(12000)
const body = await p.evaluate(() => document.body.innerText.replace(/\s+/g, ' '))
console.log('BODY:', body.slice(0, 700))
console.log('has Submit Solution btn:', await p.evaluate(() => [...document.querySelectorAll('button')].some((e) => /submit solution/i.test(e.textContent))))
await b.close()
